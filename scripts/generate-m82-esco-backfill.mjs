import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const INPUT = '.prisma-data/knowledge-sources/competency-classification-m82-v2';
const MIGRATIONS = 'supabase/migrations';
const SOURCE_HASH = '1b5e5356d4037cdd5c938131b385b9059a1e5f256ca621e8372b6633ec9aea80';
const CLASSIFIER_VERSION = 'prisma-competency-classification-1.1.0';
const SOURCE_VERSION = 'ESCO-1.2.1';
const MODEL = 'gpt-5.6-terra';
const ALLOWED = new Set(['H1','H2','H3','H4','H5','S1','S2','S3','S4','pending']);
const COLLISIONS = [
  ['1dabb413-18e8-48ed-a963-44978e67ad32','8a8bf6e7-a404-4c7f-9e89-ce2e15980913'],
  ['795f25e5-7989-4e60-9be7-8b1b686a1547','9437a218-22d2-4eb7-bc64-b4555eb4a95f'],
  ['2fb4b423-c1e4-407d-ba48-38032d8dcda2','8ddd7e74-d187-48a1-9009-ff06b268f6cc'],
  ['4327690a-e639-4b58-98b5-d078d6b90b07','b40584aa-7c63-4eed-9422-a9798fb95fdc'],
  ['2e55bf22-45f2-43f6-8aa0-28894263313d','b979d9ae-37c2-4d1f-b8b8-7539f913cb19'],
  ['2db2667c-bbaf-4e30-8640-c9a647bd2512','e80f9e50-71ff-4bb7-8b7d-eb232685d17f'],
];
const URI_PREFIX = 'http://data.europa.eu/esco/skill/';

async function decisions() {
  const names = (await readdir(INPUT)).filter(name=>/^chunk-\d{5}\.json$/.test(name)).sort();
  if (names.length!==697) throw new Error(`Esperados 697 chunks; encontrados ${names.length}`);
  const values=[];
  for (const name of names) {
    const chunk=JSON.parse(await readFile(path.join(INPUT,name),'utf8'));
    if (chunk.sourceHash!==SOURCE_HASH || chunk.promptVersion!==CLASSIFIER_VERSION || chunk.sourceVersion!==SOURCE_VERSION || chunk.model!==MODEL)
      throw new Error(`Metadados divergentes: ${name}`);
    values.push(...chunk.decisions);
  }
  const byUri=new Map(values.map(row=>[row.uri,row]));
  if (values.length!==13939 || byUri.size!==13939) throw new Error('Catálogo incompleto ou URIs duplicadas');
  const adjudicationDir='.prisma-data/knowledge-sources/competency-classification-m82-adjudication';
  const adjudicationFiles=(await readdir(adjudicationDir)).filter(name=>/^chunk-\d{5}\.json$/.test(name)).sort();
  if (adjudicationFiles.length!==82) throw new Error('Adjudicação incompleta');
  const adjudicated=new Set();
  for (const name of adjudicationFiles) {
    const record=JSON.parse(await readFile(path.join(adjudicationDir,name),'utf8'));
    if (record.version!=='prisma-competency-adjudication-1.0.0') throw new Error(`Adjudicação incompatível: ${name}`);
    for (const decision of record.decisions) {
      const original=byUri.get(decision.uri);
      if (!original || adjudicated.has(decision.uri) || original.category!==decision.primaryCategory ||
        !ALLOWED.has(decision.category) || !decision.reason?.trim() || decision.reason.length>300 ||
        !['high','medium','low'].includes(decision.certainty)) throw new Error(`Adjudicação inválida: ${decision.uri}`);
      adjudicated.add(decision.uri);
      byUri.set(decision.uri,{...original,category:decision.certainty==='low'?'pending':decision.category,
        reason:decision.reason.trim(),certainty:`adjudicated_${decision.certainty}`});
    }
  }
  if (adjudicated.size!==820) throw new Error(`Esperadas 820 decisões adjudicadas; encontradas ${adjudicated.size}`);
  const overrideFile='scripts/m82-esco-classification-overrides.json';
  let overrides=[];
  try { overrides=JSON.parse(await readFile(overrideFile,'utf8')); }
  catch(error) { if (error.code!=='ENOENT') throw error; }
  if (!Array.isArray(overrides)) throw new Error('Overrides devem ser uma lista');
  for (const override of overrides) {
    const original=byUri.get(override.uri);
    if (!original || !ALLOWED.has(override.category) || !override.reason?.trim() || override.reason.length>300)
      throw new Error(`Override inválido: ${override.uri}`);
    byUri.set(override.uri,{...original,category:override.category,reason:override.reason.trim(),certainty:'reviewed'});
  }
  for (const [first,second] of COLLISIONS) {
    const a=byUri.get(URI_PREFIX+first),b=byUri.get(URI_PREFIX+second);
    if (!a || !b || a.category!==b.category) throw new Error(`Conceito canônico com duas classificações: ${first}, ${second}`);
  }
  const result=[...byUri.values()].sort((a,b)=>a.uri.localeCompare(b.uri));
  for (const row of result) {
    if (!row.uri.startsWith(URI_PREFIX) || !ALLOWED.has(row.category) || !row.reason?.trim() || row.reason.length>300)
      throw new Error(`Decisão inválida: ${row.uri}`);
  }
  return result;
}

function migration(rows,index) {
  const data=JSON.stringify(rows.map(row=>({uri:row.uri,category:row.category,reason:row.reason,certainty:row.certainty})));
  if (data.includes('$m82_json$')) throw new Error('Delimitador SQL presente nos dados');
  return `-- M8.2 ESCO 1.2.1 assisted classification, batch ${index+1}; generated by scripts/generate-m82-esco-backfill.mjs.
-- Source SHA-256: ${SOURCE_HASH}. Only current unclassified global skill concepts are inserted.
do $m82$
declare
  v_input jsonb := $m82_json$${data}$m82_json$::jsonb;
  v_found integer;
begin
  select count(distinct item.uri) into v_found
  from jsonb_to_recordset(v_input) as item(uri text, category text, reason text, certainty text)
  join public.knowledge_external_mappings mapping on mapping.external_uri = item.uri
  join public.knowledge_sources source on source.id = mapping.source_id and source.name = 'ESCO'
  join public.knowledge_source_versions source_version on source_version.id = mapping.source_version_id
    and source_version.external_version = '1.2.1' and source_version.import_status = 'published'
  join public.knowledge_concepts concept on concept.id = mapping.concept_id
    and concept.scope = 'global' and concept.status = 'approved'
    and concept.concept_type not in ('occupation','certification');
  if v_found <> jsonb_array_length(v_input) then
    raise exception 'M82_ESCO_MAPPING_MISMATCH: found %, expected %', v_found, jsonb_array_length(v_input);
  end if;
  if exists (
    select mapping.concept_id
    from jsonb_to_recordset(v_input) as item(uri text, category text, reason text, certainty text)
    join public.knowledge_external_mappings mapping on mapping.external_uri = item.uri
    join public.knowledge_sources source on source.id = mapping.source_id and source.name = 'ESCO'
    group by mapping.concept_id having count(distinct item.category)>1
  ) then raise exception 'M82_ESCO_CANONICAL_CLASS_CONFLICT'; end if;
  insert into public.knowledge_competency_classifications
    (concept_id, subgroup_id, version, taxonomy_version, method, provenance)
  select distinct on (concept.id)
    concept.id, subgroup.id,
    coalesce((select max(history.version)+1 from public.knowledge_competency_classifications history
      where history.concept_id=concept.id),1),
    'competency-taxonomy-2.0.0', 'ai_assisted',
    jsonb_build_object('source','ESCO','sourceVersion','1.2.1','sourceURI',item.uri,
      'sourceHash','${SOURCE_HASH}',
      'classifierVersion','${CLASSIFIER_VERSION}',
      'model','${MODEL}', 'reason',item.reason,'certainty',item.certainty,
      'agreement','M8.2-1.0.0')
  from jsonb_to_recordset(v_input) as item(uri text, category text, reason text, certainty text)
  join public.knowledge_external_mappings mapping on mapping.external_uri = item.uri
  join public.knowledge_sources source on source.id = mapping.source_id and source.name = 'ESCO'
  join public.knowledge_source_versions source_version on source_version.id = mapping.source_version_id
    and source_version.external_version = '1.2.1' and source_version.import_status = 'published'
  join public.knowledge_concepts concept on concept.id = mapping.concept_id
    and concept.scope = 'global' and concept.status = 'approved'
    and concept.concept_type not in ('occupation','certification')
  join public.competency_subgroups subgroup on subgroup.code=item.category and subgroup.scope='global' and subgroup.status='active'
  where not exists (select 1 from public.knowledge_competency_classifications current_class
    where current_class.concept_id=concept.id and current_class.is_current)
  order by concept.id,item.uri;
end $m82$;
`;
}

const all=await decisions();
const selected=all.filter(row=>row.category!=='pending');
const batchSize=1000;
for (let offset=0;offset<selected.length;offset+=batchSize) {
  const index=offset/batchSize;
  const file=path.join(MIGRATIONS,`2026092013${String(index+1).padStart(4,'0')}_m82_esco_classification_${String(index+1).padStart(2,'0')}.sql`);
  await writeFile(file,migration(selected.slice(offset,offset+batchSize),index),{flag:'wx'});
}
console.log(JSON.stringify({sourceCount:all.length,classified:selected.length,pending:all.length-selected.length,
  migrationCount:Math.ceil(selected.length/batchSize),adjudicated:all.filter(row=>row.certainty?.startsWith('adjudicated_')).length,
  overrides:all.filter(row=>row.certainty==='reviewed').length}));
